-- Sabai Sabai — PostgreSQL schema for M3 Air
-- Run: psql -U postgres -d sabai sabai -f scripts/migrate/schema.sql

BEGIN;

-- === companions (core listings) ===
CREATE TABLE IF NOT EXISTS companions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    age INTEGER,
    location TEXT,
    city TEXT,
    price TEXT,
    description TEXT,
    image_url TEXT,
    rating NUMERIC(3, 1) DEFAULT 0.0,
    reviews INTEGER DEFAULT 0,
    availability TEXT,
    tags JSONB DEFAULT '[]'::jsonb,
    metrics JSONB DEFAULT '{}'::jsonb,
    phone TEXT,
    phone_normalized TEXT,
    hours TEXT,
    line_url TEXT,
    telegram_url TEXT,
    maps_url TEXT,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    source_channel TEXT,
    source_target TEXT,
    canonical_key TEXT,
    mention_count INTEGER DEFAULT 0,
    is_safe_image BOOLEAN DEFAULT TRUE,
    compliance_tier TEXT DEFAULT 'unclassified',
    raw_text TEXT,
    source_message_ids JSONB DEFAULT '[]'::jsonb,
    photo_urls JSONB DEFAULT '[]'::jsonb,
    drive_photo_urls JSONB DEFAULT '[]'::jsonb,
    all_photo_urls JSONB DEFAULT '[]'::jsonb,
    discussion_notes TEXT,
    user_feedback JSONB DEFAULT '[]'::jsonb,
    user_feedback_summary TEXT,
    user_rating NUMERIC(3,1),
    service_tags JSONB DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_companions_phone_normalized
  ON companions(phone_normalized)
  WHERE phone_normalized IS NOT NULL AND phone_normalized <> '';

CREATE UNIQUE INDEX IF NOT EXISTS idx_companions_canonical_key
  ON companions(canonical_key)
  WHERE canonical_key IS NOT NULL AND canonical_key <> '';

CREATE INDEX IF NOT EXISTS idx_companions_updated_at ON companions(updated_at DESC);
CREATE INDEX IF NOT EXISTS idx_companions_city ON companions(city);
CREATE INDEX IF NOT EXISTS idx_companions_source_channel ON companions(source_channel);
CREATE INDEX IF NOT EXISTS idx_companions_compliance_tier ON companions(compliance_tier);

-- === channel_messages (raw archive) ===
CREATE TABLE IF NOT EXISTS channel_messages (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    telegram_message_id BIGINT NOT NULL,
    channel_id TEXT NOT NULL,
    channel_name TEXT,
    sender_id TEXT,
    message_text TEXT,
    message_date TIMESTAMPTZ,
    has_media BOOLEAN DEFAULT FALSE,
    media_type TEXT,
    photo_url TEXT,
    reply_to_message_id BIGINT,
    grouped_id TEXT,
    cluster_id INTEGER,
    message_type TEXT NOT NULL DEFAULT 'unknown',
    linked_companion_id BIGINT REFERENCES companions(id) ON DELETE SET NULL,
    raw_json JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE(channel_id, telegram_message_id)
);

CREATE INDEX IF NOT EXISTS idx_channel_messages_date ON channel_messages (message_date DESC);
CREATE INDEX IF NOT EXISTS idx_channel_messages_type ON channel_messages (message_type);
CREATE INDEX IF NOT EXISTS idx_channel_messages_channel ON channel_messages (channel_id);

-- === photo_archive (photo metadata) ===
CREATE TABLE IF NOT EXISTS photo_archive (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    telegram_message_id BIGINT NOT NULL,
    channel_id TEXT NOT NULL,
    channel_name TEXT,
    sender_id TEXT,
    message_date TIMESTAMPTZ,
    original_filename TEXT,
    stored_filename TEXT,
    local_path TEXT,
    supabase_url TEXT,
    file_size_bytes INTEGER,
    media_type TEXT,
    mime_type TEXT,
    photo_telegram_id BIGINT,
    grouped_id TEXT,
    linked_companion_id BIGINT REFERENCES companions(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE(channel_id, telegram_message_id, stored_filename)
);

CREATE INDEX IF NOT EXISTS idx_photo_archive_channel ON photo_archive (channel_id);
CREATE INDEX IF NOT EXISTS idx_photo_archive_date ON photo_archive (message_date DESC);

-- === page_views (visitor tracking) ===
CREATE TABLE IF NOT EXISTS page_views (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    session_id UUID NOT NULL,
    page TEXT,
    referrer TEXT,
    user_agent TEXT,
    language TEXT,
    screen_w INTEGER,
    screen_h INTEGER,
    country TEXT,
    city TEXT,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    ip_address TEXT,
    country_code TEXT,
    region TEXT,
    timezone TEXT,
    org TEXT,
    listing_id BIGINT REFERENCES companions(id) ON DELETE SET NULL,
    event_type TEXT DEFAULT 'page_view',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_page_views_session ON page_views (session_id);
CREATE INDEX IF NOT EXISTS idx_page_views_created ON page_views (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_page_views_listing ON page_views (listing_id);

-- === signals (demand signals) ===
CREATE TABLE IF NOT EXISTS signals (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    session_id UUID NOT NULL,
    listing_id BIGINT REFERENCES companions(id) ON DELETE SET NULL,
    signal_type TEXT NOT NULL CHECK (signal_type IN ('save', 'inquire', 'share')),
    payload JSONB DEFAULT '{}'::jsonb,
    country TEXT,
    city TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_signals_listing ON signals(listing_id);
CREATE INDEX IF NOT EXISTS idx_signals_type ON signals(signal_type);
CREATE INDEX IF NOT EXISTS idx_signals_created ON signals(created_at DESC);

COMMIT;