/**
 * "เมือง<X>" capital-district heuristic. Only used as a last-resort fallback
 * after the explicit DISTRICT_TO_PROVINCE table fails. Province names like
 * "นครปฐม" become "เมืองนครปฐม" → 73. About 60 of 928 districts are covered
 * here; the rest depend on the table.
 */
function inferProvinceFromCapitalDistrict(districtName) {
  const m = /^เมือง(.+)$/.exec(districtName.trim());
  if (!m) return null;
  const tail = m[1].trim();
  const direct = LOOKUP.get(tail);
  if (direct) return direct;
  // Common merged forms: "เพชรบุรี" matches itself but "เมืองเพชรบูรณ์" must
  // not collapse. A conservative substring check matches the long form first.
  let best = null;
  for (const [name, province] of LOOKUP) {
    if (name.length < 4) continue;
    if (tail.includes(name) && (!best || name.length > best.name.length)) {
      best = { name, province };
    }
  }
  return best ? best.province : null;
}

/** Look up a province by district name; returns null if ambiguous or unknown. */
export function resolveDistrictToProvince(districtName) {
  if (!districtName) return null;
  const cleaned = normalizeAdminName(districtName);
  if (!cleaned) return null;
  const fromTable = DISTRICT_TO_PROVINCE.get(districtName.trim());
  if (fromTable != null) return PROVINCE_BY_CODE.get(fromTable) ?? null;
  const code = inferProvinceFromCapitalDistrict(districtName);
  return code ?? null;
}

/**
 * Resolve a province from anything a source row offers: a TIS-1099 code, a Thai
 * name, a romanisation, an ISO code, or a free-text address containing one.
 * Returns null rather than guessing — an unresolved province must stay visible
 * as unresolved, never be silently defaulted to Bangkok.
 */
export function resolveProvince(value) {
  if (value == null || value === '') return null;

  if (typeof value === 'number' || /^\d{1,2}$/.test(String(value).trim())) {
    return PROVINCE_BY_CODE.get(Number(value)) ?? null;
  }

  const raw = String(value);
  const key = normalizeAdminName(raw);
  if (!key) return null;

  const direct = LOOKUP.get(key);
  if (direct) return direct;

  // Free-text address: find the longest province name contained in the string.
  // Longest-first prevents "นคร" style prefixes matching the wrong province.
  let best = null;
  for (const [name, province] of LOOKUP) {
    if (name.length < 4) continue;
    if (key.includes(name) && (!best || name.length > best.name.length)) {
      best = { name, province };
    }
  }
  return best ? best.province : null;
}
